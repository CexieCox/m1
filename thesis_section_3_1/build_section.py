from pathlib import Path
from copy import deepcopy
import hashlib, json
from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor
from lxml import etree

root = Path(__file__).parent
source = root / 'Capstone_Project_English_final.docx'
output = root / 'Section_3_1_Dataset_With_WinMET.docx'
source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
doc = Document(source)
body = doc._element.body
children = list(body)
def text_of(el):
    return ''.join(t.text or '' for t in el.iter(qn('w:t')))
start = next(i for i,e in enumerate(children) if text_of(e).strip() == '3.1. Dataset')
end = next(i for i,e in enumerate(children[start+1:],start+1) if text_of(e).strip() == '3.2. Model Framework')
original = [deepcopy(e) for e in children[start:end]]
original_xml = [etree.tostring(e,method='c14n',exclusive=True) for e in original]
# The first section-properties node after the extract governs its page geometry.
sect = None
for e in children[start:]:
    pp = e.find(qn('w:pPr'))
    candidates = [e] if e.tag == qn('w:sectPr') else ([] if pp is None else pp.findall(qn('w:sectPr')))
    if candidates:
        sect = deepcopy(candidates[0])
        break
assert sect is not None
for tag in ['w:headerReference','w:footerReference','w:pgNumType','w:titlePg']:
    for e in list(sect.findall(qn(tag))):
        sect.remove(e)
for e in list(body):
    body.remove(e)
for e in original:
    body.append(e)
body.append(sect)

heading = doc.add_paragraph(style='Normal')
heading.paragraph_format.page_break_before = True
heading.paragraph_format.keep_with_next = True
heading.paragraph_format.space_after = Pt(10)
r=heading.add_run('WinMET execution logs')
r.bold=True
r.font.color.rgb=RGBColor(0,0,0)

added = [
    'The sandbox telemetry used in this study is obtained from the Windows Malware Execution Traces (WinMET) dataset, version v3, published on Zenodo by Raducu et al. (2025). The release contains 31,844 execution traces distributed across five volumes. Each trace is a JSON report generated by CAPE Sandbox and records spawned processes, sequences of Windows API and system calls, call parameters, return values, and accessed operating-system resources. The study reuses these existing reports as its source of malware execution logs.',
    'WinMET also provides report-to-label mappings from CAPE and AVClass. Its accompanying consensus-label file contains both labels for each execution trace. These labels support the initial selection and review of loader-related reports. The local filtering tool selects candidate reports from WinMET; a family-label match is a selection cue and does not by itself establish that a particular loader behavior was observed during execution.',
    'The filtering tool was run across all five WinMET volumes. Because the CTI corpus was frozen for the experiments, the study limited the source-log pool used in the project to 12,738 reports. Filtering this pool yielded 1,390 loader candidates, from which 1,036 filtered log files were selected for the thesis experiments. The selected files belong to the 2021 and 2024 partitions. The figure of 1,036 counts input log files; event counts and episode counts describe different units produced during downstream processing.',
    'Within TemporalKG-Hunt, CTI reports provide narrative descriptions of adversary behavior, while WinMET reports provide observations of malware execution for subsequent event normalization and transition construction. The log-selection procedure is described in Section 3.2.2, the collection results in Section 4.2, and downstream processing in Section 4.3.'
]
for text in added:
    p=doc.add_paragraph(text,style='Normal')
    p.paragraph_format.widow_control=True

p=doc.add_paragraph(style='Normal')
p.paragraph_format.keep_with_next=True
p.paragraph_format.space_before=Pt(8)
p.add_run('Dataset reference').bold=True
p=doc.add_paragraph('Raducu, R., Villagrasa-Labrador, A., Rodríguez, R. J., and Álvarez, P. (2025). WinMET Dataset (Version v3) [Data set]. Zenodo. https://doi.org/10.5281/zenodo.16414116.',style='Normal')
p.paragraph_format.widow_control=True
doc.core_properties.title='Section 3.1 Dataset with WinMET execution logs'
doc.core_properties.subject='Original Section 3.1 preserved with a WinMET dataset addition'
doc.save(output)

check=Document(output)
assert [etree.tostring(e,method='c14n',exclusive=True) for e in list(check._element.body)[:len(original_xml)]] == original_xml
assert hashlib.sha256(source.read_bytes()).hexdigest() == source_hash
assert all(text in [p.text for p in check.paragraphs] for text in added)
(root/'validation.json').write_text(json.dumps({'source_sha256':source_hash,'original_body_elements_preserved':len(original_xml),'added_paragraphs':len(added),'output_sha256':hashlib.sha256(output.read_bytes()).hexdigest()},indent=2),encoding='utf-8')
print('Original Section 3.1 preserved verbatim, including paragraph and list formatting.')
print(output)
